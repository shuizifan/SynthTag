$ErrorActionPreference = 'Stop'
$testRoot = Join-Path ([IO.Path]::GetTempPath()) ('SynthTag-metadata-test-' + [Guid]::NewGuid().ToString('N'))
$previousLocalAppData = $env:LOCALAPPDATA
$script:passed = 0
$script:failed = New-Object 'Collections.Generic.List[string]'
$script:caseLogs = New-Object 'Collections.Generic.List[string]'
function Assert-True([bool]$Condition, [string]$Message) {
    if (-not $Condition) { throw "ASSERTION FAILED: $Message" }
}
function Run-Case([string]$Name, [scriptblock]$Body) {
    $script:caseLogs.Clear()
    try { & $Body; $script:passed++; Write-Output "PASS: $Name" }
    catch {
        $script:failed.Add($Name + ': ' + $_.Exception.Message)
        Write-Output "FAIL: $Name -- $($_.Exception.Message)"
        foreach ($log in $script:caseLogs) { Write-Output "  $log" }
    }
}
function New-TestImage([string]$Name, [string]$Format = 'png') {
    $path = Join-Path $testRoot $Name
    if ($Format -eq 'webp') {
        # 8x8 lossless RGB image generated by Pillow 12.3; no runtime dependency.
        [IO.File]::WriteAllBytes($path, [Convert]::FromBase64String('UklGRiQAAABXRUJQVlA4TBcAAAAvB8ABAA8Q8x/zHwYFaRuwKDsR/Q8cAAA='))
        return $path
    }
    $bitmap = New-Object Drawing.Bitmap(8, 8)
    try {
        $bitmap.SetPixel(2, 3, [Drawing.Color]::Red)
        $imageFormat = switch ($Format) {
            'jpeg' { [Drawing.Imaging.ImageFormat]::Jpeg }
            'tiff' { [Drawing.Imaging.ImageFormat]::Tiff }
            default { [Drawing.Imaging.ImageFormat]::Png }
        }
        $bitmap.Save($path, $imageFormat)
    } finally { $bitmap.Dispose() }
    return $path
}
function File-Hash([string]$Path) {
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash
}
function Assert-ReadableImage([string]$Path) {
    $source = [Drawing.Image]::FromFile($Path)
    try {
        $decoded = New-Object Drawing.Bitmap($source)
        try { Assert-True ($decoded.Width -eq 8 -and $decoded.Height -eq 8) 'Image pixels remain decodable.' }
        finally { $decoded.Dispose() }
    } finally { $source.Dispose() }
}
function Read-Subjects([string]$Path) {
    $map = Get-Subjects -Files @($Path)
    $key = [IO.Path]::GetFullPath($Path).ToLowerInvariant()
    Assert-True ($map.ContainsKey($key)) 'Readable image is present in subject map.'
    return ,@($map[$key])
}
function Assert-SafeFailure($Result, [string]$Path, [string]$OriginalHash) {
    Assert-True (-not $Result.Success) 'Failure is not reported as success.'
    Assert-True ([bool]$Result.Error) 'Failure includes actionable error text.'
    Assert-True ((File-Hash $Path) -eq $OriginalHash) 'Failure preserves original bytes.'
}
try {
    $null = New-Item -ItemType Directory -Path $testRoot
    $env:LOCALAPPDATA = $testRoot
    Add-Type -AssemblyName System.Drawing
    $script:RuntimeRoot = Join-Path $testRoot 'SynthTag'
    $script:ExifTool = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\exiftool_bin\exiftool.exe'))
    $ExifTool = $script:ExifTool
    $TAG = 'contains-synthetic-performer'
    function Write-AppLog {
        param($Level, $Message, $Data)
        $detail = @()
        foreach ($key in $Data.Keys) { $detail += ($key + '=' + [string]$Data[$key]) }
        $script:caseLogs.Add($Level + ' ' + $Message + ': ' + ($detail -join '; '))
    }
    $module = Join-Path $PSScriptRoot '..\metadata.ps1'
    Assert-True (Test-Path -LiteralPath $module) 'Metadata module exists.'
    . $module

    Run-Case 'PNG/JPEG Chinese and bracket filenames: add, preserve keywords, remove, decode' {
        foreach ($fixture in @(@('中文[测试]图片.png', 'png'), @('照片[01].jpg', 'jpeg'))) {
            $path = New-TestImage $fixture[0] $fixture[1]
            $seed = Invoke-ExifTool -ExifArgs @('-overwrite_original', '-XMP-dc:Subject=客户标签') -Files @($path)
            Assert-True ($seed.ExitCode -eq 0) 'Fixture metadata seeded successfully.'
            $result = Set-SafeFileTag -File $path -Mode add -KeepBackup $false
            Assert-True $result.Success ('Add succeeds: ' + $result.Error)
            $subjects = Read-Subjects $path
            Assert-True (@($subjects | Where-Object { $_ -eq $TAG }).Count -eq 1) 'Adds precisely one AI tag.'
            Assert-True ($subjects -contains '客户标签') 'Preserves unrelated keywords.'
            Assert-ReadableImage $path
            $result = Set-SafeFileTag -File $path -Mode remove -KeepBackup $false
            Assert-True $result.Success ('Remove succeeds: ' + $result.Error)
            $subjects = Read-Subjects $path
            Assert-True ($subjects -notcontains $TAG) 'Removes AI tag.'
            Assert-True ($subjects -contains '客户标签') 'Remove preserves unrelated keywords.'
            Assert-ReadableImage $path
        }
    }
    Run-Case 'Normalize duplicate tags while preserving unrelated keywords' {
        $path = New-TestImage '重复标签.png'
        $seed = Invoke-ExifTool -ExifArgs @('-overwrite_original', '-XMP-dc:Subject=', '-XMP-dc:Subject+=other', "-XMP-dc:Subject+=$TAG", "-XMP-dc:Subject+=$TAG") -Files @($path)
        Assert-True ($seed.ExitCode -eq 0) 'Duplicate fixture was written.'
        Assert-True ((Get-FileState -subjects (Read-Subjects $path)) -eq 'duplicate') 'Fixture actually contains duplicate AI tags.'
        $result = Set-SafeFileTag -File $path -Mode normalize -KeepBackup $false
        Assert-True $result.Success ('Normalize succeeds: ' + $result.Error)
        $subjects = Read-Subjects $path
        Assert-True (@($subjects | Where-Object { $_ -eq $TAG }).Count -eq 1) 'Normalize produces one AI tag.'
        Assert-True ($subjects -contains 'other') 'Normalize preserves unrelated keywords.'
    }
    Run-Case 'TIFF and WebP support add/remove while preserving image data' {
        foreach ($fixture in @(@('格式[测试].tiff', 'tiff'), @('网页格式[测试].webp', 'webp'))) {
            $path = New-TestImage $fixture[0] $fixture[1]
            $before = Invoke-ExifTool -ExifArgs @('-j', '-ImageDataHash', '-api', 'ImageHashType=SHA256') -Files @($path)
            $beforeData = ConvertFrom-Json -InputObject $before.StdOut
            Assert-True ([bool]$beforeData.ImageDataHash) 'Format fixture has a content digest.'
            $result = Set-SafeFileTag -File $path -Mode add -KeepBackup $false
            Assert-True $result.Success ('Format add succeeds: ' + $result.Error)
            Assert-True ((Read-Subjects $path) -contains $TAG) 'Format contains requested tag.'
            $result = Set-SafeFileTag -File $path -Mode remove -KeepBackup $false
            Assert-True $result.Success ('Format remove succeeds: ' + $result.Error)
            Assert-True ((Read-Subjects $path) -notcontains $TAG) 'Format removes requested tag.'
            $after = Invoke-ExifTool -ExifArgs @('-j', '-ImageDataHash', '-api', 'ImageHashType=SHA256') -Files @($path)
            $afterData = ConvertFrom-Json -InputObject $after.StdOut
            Assert-True ($beforeData.ImageDataHash -eq $afterData.ImageDataHash) 'Format content digest is unchanged.'
            if ($fixture[1] -eq 'tiff') { Assert-ReadableImage $path }
        }
    }
    Run-Case 'Valid JPEG with missing optional-for-decoding EXIF fields can be tagged with warnings' {
        $path = New-TestImage 'Photoshop式EXIF缺项.jpg' 'jpeg'
        $seed = Invoke-ExifTool -ExifArgs @('-overwrite_original', '-EXIF:UserComment=Fixture') -Files @($path)
        Assert-True ($seed.ExitCode -eq 0) 'Creates a valid JPEG EXIF directory.'
        $seed = Invoke-ExifTool -ExifArgs @('-overwrite_original', '-EXIF:ExifVersion=', '-EXIF:ComponentsConfiguration=') -Files @($path)
        Assert-True ($seed.ExitCode -eq 0) 'Creates required-metadata warnings without changing image data.'
        $before = Invoke-ExifTool -ExifArgs @('-j', '-G4', '-a', '-validate', '-warning', '-ImageDataHash', '-api', 'ImageHashType=SHA256') -Files @($path)
        $beforeData = ConvertFrom-Json -InputObject $before.StdOut
        Assert-True ([string]$beforeData.':Warning' -match 'Missing required JPEG ExifIFD tag') 'Fixture genuinely reproduces benign metadata warnings.'
        Assert-True ([bool]$beforeData.'Copy1:Warning') 'Fixture has multiple warning records.'
        Assert-ReadableImage $path
        $map = Get-Subjects -Files @($path)
        Assert-True ($map.ContainsKey($path.ToLowerInvariant())) 'Decodable JPEG is available despite metadata-only warnings.'
        $result = Set-SafeFileTag -File $path -Mode add -KeepBackup $false
        Assert-True $result.Success ('Metadata-only warning does not reject valid JPEG: ' + $result.Error)
        Assert-True ([bool]$result.Warning) 'Successful operation still surfaces metadata warnings.'
        Assert-True ((Read-Subjects $path) -contains $TAG) 'JPEG receives the requested AI tag.'
        $after = Invoke-ExifTool -ExifArgs @('-j', '-ImageDataHash', '-api', 'ImageHashType=SHA256') -Files @($path)
        $afterData = ConvertFrom-Json -InputObject $after.StdOut
        Assert-True ($beforeData.':ImageDataHash' -eq $afterData.ImageDataHash) 'JPEG compressed image data remains identical.'
        Assert-ReadableImage $path
    }
    Run-Case 'Later duplicate JSON warning cannot hide truncated image after a benign EXIF warning' {
        $path = New-TestImage '后续警告损坏.jpg' 'jpeg'
        $before = File-Hash $path
        $originalInvoke = ${function:Invoke-ExifTool}
        try {
            function Invoke-ExifTool {
                param([string[]]$ExifArgs, [string[]]$Files)
                if ($ExifArgs -contains '-validate') {
                    $record = @{
                        SourceFile = $Files[0]
                        ':FileType' = 'JPEG'
                        ':FileTypeExtension' = 'jpg'
                        ':Validate' = '2 Warnings'
                        ':ImageDataHash' = 'stable-test-image-content'
                        ':Warning' = 'Missing required JPEG ExifIFD tag 0x9000 ExifVersion'
                        'Copy1:Warning' = 'Truncated JPEG image'
                    }
                    return [pscustomobject]@{ StdOut = ($record | ConvertTo-Json -Compress); StdErr = ''; ExitCode = 0 }
                }
                & $originalInvoke -ExifArgs $ExifArgs -Files $Files
            }
            $map = Get-Subjects -Files @($path)
            Assert-True (-not $map.ContainsKey($path.ToLowerInvariant())) 'All warnings are inspected during scanning.'
            $result = Set-SafeFileTag -File $path -Mode add -KeepBackup $false
        } finally { ${function:Invoke-ExifTool} = $originalInvoke }
        Assert-SafeFailure $result $path $before
        Assert-True ($result.Error -match 'Truncated JPEG image') 'Reports the harmful warning, not only the first benign warning.'
    }
    Run-Case 'KeepBackup stores the exact original image bytes' {
        $path = New-TestImage '保留备份.png'
        $before = File-Hash $path
        $result = Set-SafeFileTag -File $path -Mode add -KeepBackup $true
        Assert-True $result.Success ('Backup operation succeeds: ' + $result.Error)
        Assert-True (Test-Path -LiteralPath ($path + '_original')) 'Creates expected original backup.'
        Assert-True ((File-Hash ($path + '_original')) -eq $before) 'Backup exactly matches source bytes.'
        Assert-ReadableImage $path
    }
    Run-Case 'Zero-byte and truncated images are unreadable and never successful writes' {
        $empty = Join-Path $testRoot '空文件.png'
        [IO.File]::WriteAllBytes($empty, [byte[]]@())
        $truncated = New-TestImage '截断.png'
        $bytes = [IO.File]::ReadAllBytes($truncated)
        [IO.File]::WriteAllBytes($truncated, [byte[]]$bytes[0..32])
        foreach ($path in @($empty, $truncated)) {
            $before = File-Hash $path
            $subjects = Get-Subjects -Files @($path)
            Assert-True (-not $subjects.ContainsKey($path.ToLowerInvariant())) 'Corrupt file is absent from readable subjects.'
            $result = Set-SafeFileTag -File $path -Mode add -KeepBackup $false
            Assert-SafeFailure $result $path $before
        }
    }
    Run-Case 'Damaged PNG checksum is rejected before original replacement' {
        $path = New-TestImage 'CRC损坏.png'
        $bytes = [IO.File]::ReadAllBytes($path)
        # Last four bytes are the IEND CRC. Altering it preserves PNG structure.
        $bytes[$bytes.Length - 1] = $bytes[$bytes.Length - 1] -bxor 1
        [IO.File]::WriteAllBytes($path, $bytes)
        $before = File-Hash $path
        Assert-SafeFailure (Set-SafeFileTag -File $path -Mode add -KeepBackup $false) $path $before
    }
    Run-Case 'Mixed healthy and unreadable files retain the healthy metadata result' {
        $healthy = New-TestImage '混合正常.png'
        $broken = Join-Path $testRoot '混合损坏.png'
        [IO.File]::WriteAllBytes($broken, [byte[]]@())
        $map = Get-Subjects -Files @($healthy, $broken)
        Assert-True ($map.ContainsKey($healthy.ToLowerInvariant())) 'Healthy item remains available when another item fails.'
        Assert-True (-not $map.ContainsKey($broken.ToLowerInvariant())) 'Broken item does not become a false untagged result.'
    }
    Run-Case 'Read-only source remains intact and reports failure' {
        $path = New-TestImage '只读.png'
        $before = File-Hash $path
        [IO.File]::SetAttributes($path, [IO.FileAttributes]::ReadOnly)
        try { Assert-SafeFailure (Set-SafeFileTag -File $path -Mode add -KeepBackup $false) $path $before }
        finally { [IO.File]::SetAttributes($path, [IO.FileAttributes]::Normal) }
    }
    Run-Case 'Exclusively locked source reports failure and preserves bytes' {
        $path = New-TestImage '被占用.png'
        $before = File-Hash $path
        $handle = [IO.File]::Open($path, [IO.FileMode]::Open, [IO.FileAccess]::ReadWrite, [IO.FileShare]::None)
        try { $result = Set-SafeFileTag -File $path -Mode add -KeepBackup $false }
        finally { $handle.Dispose() }
        Assert-SafeFailure $result $path $before
    }
    Run-Case 'Pre-existing _original and _exiftool_tmp files are never deleted or changed' {
        foreach ($keepBackup in @($false, $true)) {
            $path = New-TestImage ('既存临时文件-' + $keepBackup + '.png')
            $backupPath = $path + '_original'
            $tempPath = $path + '_exiftool_tmp'
            [IO.File]::WriteAllText($backupPath, 'A pre-existing backup must survive.')
            [IO.File]::WriteAllText($tempPath, 'A pre-existing recovery file must survive.')
            $backupHash = File-Hash $backupPath
            $tempHash = File-Hash $tempPath
            $null = Set-SafeFileTag -File $path -Mode add -KeepBackup $keepBackup
            Assert-True ((File-Hash $backupPath) -eq $backupHash) 'Existing original backup is unchanged.'
            Assert-True ((File-Hash $tempPath) -eq $tempHash) 'Existing ExifTool recovery file is unchanged.'
        }
    }
    Run-Case 'Get-Subjects rejects ExifTool JSON Error records' {
        $originalInvoke = ${function:Invoke-ExifTool}
        try {
            function Invoke-ExifTool {
                param([string[]]$ExifArgs, [string[]]$Files)
                [pscustomobject]@{ StdOut = (@{ SourceFile = $Files[0]; Error = 'Simulated read error' } | ConvertTo-Json -Compress); StdErr = ''; ExitCode = 1 }
            }
            $path = New-TestImage 'JSON错误.png'
            $map = Get-Subjects -Files @($path)
            Assert-True (-not $map.ContainsKey($path.ToLowerInvariant())) 'Error record is not treated as an untagged readable file.'
        } finally { ${function:Invoke-ExifTool} = $originalInvoke }
    }
    Run-Case 'ExifTool write failure cannot change source or report success' {
        $path = New-TestImage '写入故障.png'
        $before = File-Hash $path
        $originalInvoke = ${function:Invoke-ExifTool}
        try {
            function Invoke-ExifTool {
                param([string[]]$ExifArgs, [string[]]$Files)
                if (@($ExifArgs | Where-Object { $_ -match '^-XMP-dc:Subject(?:[=+\-]|$)' -and $_ -ne '-XMP-dc:Subject' }).Count -gt 0) {
                    return [pscustomobject]@{ StdOut = '0 image files updated'; StdErr = 'Simulated disk write failure'; ExitCode = 1 }
                }
                & $originalInvoke -ExifArgs $ExifArgs -Files $Files
            }
            $result = Set-SafeFileTag -File $path -Mode add -KeepBackup $false
        } finally { ${function:Invoke-ExifTool} = $originalInvoke }
        Assert-SafeFailure $result $path $before
    }
    Run-Case 'Final replacement failure cannot change source or report success' {
        $path = New-TestImage '提交故障.png'
        $before = File-Hash $path
        $originalComplete = ${function:Complete-SafeReplacement}
        Assert-True ($null -ne $originalComplete) 'Replacement boundary is available for failure injection.'
        try {
            function Complete-SafeReplacement { throw [IO.IOException]::new('Simulated network interruption before replacement') }
            $result = Set-SafeFileTag -File $path -Mode add -KeepBackup $false
        } finally { ${function:Complete-SafeReplacement} = $originalComplete }
        Assert-SafeFailure $result $path $before
    }
    Run-Case 'Unsupported ReplaceFile uses backed-up rename and verifies the image' {
        $path = New-TestImage 'Dokan兼容.png'
        $before = File-Hash $path
        $originalReplace = ${function:Invoke-NativeFileReplace}
        try {
            function Invoke-NativeFileReplace { throw (New-Object ComponentModel.Win32Exception(50)) }
            $result = Set-SafeFileTag -File $path -Mode add -KeepBackup $true
        } finally { ${function:Invoke-NativeFileReplace} = $originalReplace }
        Assert-True $result.Success ('Unsupported-operation fallback succeeds: ' + $result.Error)
        Assert-True ((Read-Subjects $path) -contains $TAG) 'Fallback writes the requested tag.'
        Assert-True ((File-Hash ($path + '_original')) -eq $before) 'Fallback backup matches exact original bytes.'
        Assert-ReadableImage $path
    }
    Run-Case 'Fallback rename failure retains original and recovery material' {
        $path = New-TestImage 'Dokan重命名失败.png'
        $before = File-Hash $path
        $originalReplace = ${function:Invoke-NativeFileReplace}
        $originalMove = ${function:Invoke-NativeMoveReplacement}
        try {
            function Invoke-NativeFileReplace { throw (New-Object ComponentModel.Win32Exception(50)) }
            function Invoke-NativeMoveReplacement { throw (New-Object ComponentModel.Win32Exception(64)) }
            $result = Set-SafeFileTag -File $path -Mode add -KeepBackup $true
        } finally {
            ${function:Invoke-NativeFileReplace} = $originalReplace
            ${function:Invoke-NativeMoveReplacement} = $originalMove
        }
        Assert-SafeFailure $result $path $before
        Assert-True ((File-Hash ($path + '_original')) -eq $before) 'Failed fallback retains backup.'
        Assert-True ([bool]$result.RecoveryPath) 'Failed commit identifies local recovery directory.'
        Assert-True (Test-Path -LiteralPath $result.RecoveryPath) 'Recovery directory remains available.'
    }
    Run-Case 'Permission failure never enters the compatibility rename path' {
        $path = New-TestImage '权限拒绝.png'
        $before = File-Hash $path
        $originalReplace = ${function:Invoke-NativeFileReplace}
        $originalMove = ${function:Invoke-NativeMoveReplacement}
        $script:unexpectedFallback = $false
        try {
            function Invoke-NativeFileReplace { throw (New-Object ComponentModel.Win32Exception(5)) }
            function Invoke-NativeMoveReplacement { $script:unexpectedFallback = $true; throw 'Fallback must not execute for permission errors.' }
            $result = Set-SafeFileTag -File $path -Mode add -KeepBackup $false
        } finally {
            ${function:Invoke-NativeFileReplace} = $originalReplace
            ${function:Invoke-NativeMoveReplacement} = $originalMove
        }
        Assert-SafeFailure $result $path $before
        Assert-True (-not $script:unexpectedFallback) 'Permission errors cannot bypass the original error through rename.'
    }
    # This exercises UNC syntax only when an existing administrative share is accessible.
    # It never creates a Windows share and cannot substitute for a real remote SMB test.
    Run-Case 'UNC fixture when localhost administrative share is available' {
        $driveRoot = [IO.Path]::GetPathRoot($testRoot)
        $uncRoot = '\\localhost\' + $driveRoot.Substring(0, 1) + '$\' + $testRoot.Substring(3)
        if (Test-Path -LiteralPath $uncRoot -ErrorAction SilentlyContinue) {
            $localPath = New-TestImage 'UNC共享[测试].png'
            $uncPath = Join-Path $uncRoot ([IO.Path]::GetFileName($localPath))
            $result = Set-SafeFileTag -File $uncPath -Mode add -KeepBackup $false
            Assert-True $result.Success ('UNC add succeeds: ' + $result.Error)
            Assert-True ((Read-Subjects $localPath) -contains $TAG) 'UNC write updates the original fixture.'
            Assert-ReadableImage $localPath
        } else { Write-Output 'SKIP: localhost administrative share unavailable; real remote SMB testing remains required.' }
    }
    if ($script:failed.Count -gt 0) { throw ($script:failed.Count.ToString() + ' case(s) failed: ' + ($script:failed -join '; ')) }
    Write-Output ('PASS: all ' + $script:passed + ' metadata cases.')
} finally {
    $env:LOCALAPPDATA = $previousLocalAppData
    if (Test-Path -LiteralPath $testRoot) {
        $resolved = [IO.Path]::GetFullPath($testRoot)
        $expected = [IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd('\') + '\SynthTag-metadata-test-'
        if (-not $resolved.StartsWith($expected, [StringComparison]::OrdinalIgnoreCase)) { throw 'Unsafe fixture cleanup path.' }
        Remove-Item -LiteralPath $testRoot -Recurse -Force
    }
}
